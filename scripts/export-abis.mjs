// Exports ABIs from Foundry build output into the shared SDK as typed `as const` modules.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const out = join(root, "packages/contracts/out");
const dest = join(root, "packages/sdk/src/abi");

for (const [file, name, exportName] of [
  ["RePayAccount.sol", "RePayAccount", "repayAccountAbi"],
  ["RePayAccountFactory.sol", "RePayAccountFactory", "repayAccountFactoryAbi"],
]) {
  const { abi } = JSON.parse(readFileSync(join(out, file, `${name}.json`), "utf8"));
  writeFileSync(
    join(dest, `${name}.ts`),
    `// Generated by scripts/export-abis.mjs from packages/contracts. Do not edit.\nexport const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
  console.log(`wrote ${name}.ts (${abi.length} entries)`);
}
